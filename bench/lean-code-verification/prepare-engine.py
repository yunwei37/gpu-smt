"""Preserve pinned original code-verification sources in the Rust Batch input."""
import argparse,gzip,json,re,runpy
from pathlib import Path

def prepare_bv_files(rows,out):
    # Lexical source discovery only. Never use this key as a proof verdict.
    strip=runpy.run_path(str(Path(__file__).resolve().parents[1]/
        'lean-candidate-scheduling/analyze.py'))['strip_comments']
    sources=sorted((row for row in rows if row['path'].endswith('.lean')
        and re.search(r'\bbv_decide\b',strip(row['text']))),key=lambda row:row['path'])
    if not sources:
        raise ValueError('No comment-stripped bv_decide source files in archive')
    assert len({row['path']for row in sources})==len(sources)
    assert {row['repository']for row in sources}=={'opencompl/lean-mlir'}
    assert {row['commit']for row in sources}=={'b8c4a771319a044854a4bbb49b8821381ef86ff8'}
    out.mkdir(exist_ok=False)
    (out/'inputs').mkdir()
    manifest=[]
    for index,row in enumerate(sources):
        name=f'inputs/{index:04d}.json.gz'
        candidate=dict(id=row['path'],task_id=None,code=row['text'],reuse=False)
        with gzip.open(out/name,'xt',encoding='utf8')as stream:
            json.dump(dict(mode='all',candidates=[candidate]),stream,ensure_ascii=False)
            stream.write('\n')
        manifest.append({**{key:row[key]for key in ['repository','commit','path']},
            'input':name,'source_bytes':len(row['text'].encode())})
    (out/'source-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    (out/'README.md').write_text("""# Original lean-mlir files mentioning bv_decide

Each input is one complete,unchanged original file from the pinned archive.
Selection is a comment-stripped lexical word match,not a Lean parse,tactic
invocation count,profile or official benchmark definition. Macro definitions,
tests,admissions and native errors are not removed. No proof is executed here.

One Batch per original module preserves separate source-file/backend contexts;
do not feed all modules to one fixed --source-file backend. The root Lake
manifest,toolchain,library arguments and original filename must be qualified
for each file before native execution. Do not infer dependency pins from the
nearest subproject or claim that the single completed module qualifies these.
The existing300s engine default is not a published lean-mlir timeout.

All mode,reuse=false,original source bytes. Native runs must use the sole free
collection slot and current48GiB aggregate/CPU8-11 contract. No runner,queue,
prover baseline,GPU method or automatic native launch is created.
""")
    print(json.dumps(dict(candidates=len(sources),
        source_bytes=sum(len(row['text'].encode())for row in sources),
        source_changed=False,new_native_executions=0)))

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input',required=True,type=Path)
    parser.add_argument('--out',required=True,type=Path)
    parser.add_argument('--workload',choices=['verina','leanmlir'],default='verina')
    parser.add_argument('--bv-decide-files',action='store_true',
        help='prepare every lexical bv_decide Lean file as a separate Batch; leanmlir only')
    args=parser.parse_args()
    if args.bv_decide_files and args.workload!='leanmlir':
        parser.error('--bv-decide-files requires --workload leanmlir')
    with gzip.open(args.input,'rt',encoding='utf8') as stream:
        rows=[json.loads(line)for line in stream]
    if args.bv_decide_files:
        prepare_bv_files(rows,args.out)
        return
    if args.workload=='leanmlir':
        target='SSA/Projects/SLLVM/Evaluation/AliveAutoGeneratedCopy.lean'
        sources=[row for row in rows if row['path']==target]
        assert len(sources)==1
        row=sources[0]
        assert row['repository']=='opencompl/lean-mlir'
        assert row['commit']=='b8c4a771319a044854a4bbb49b8821381ef86ff8'
        # Keep the entire module: splitting by tactic/theorem would drop its
        # definitions, scoped syntax and dependencies and change the workload.
        candidate=dict(id=target,task_id=None,code=row['text'],reuse=False)
        args.out.mkdir(exist_ok=False)
        with gzip.open(args.out/'all.json.gz','xt',encoding='utf8')as stream:
            json.dump(dict(mode='all',candidates=[candidate]),stream,ensure_ascii=False)
            stream.write('\n')
        (args.out/'source-manifest.json').write_text(json.dumps(
            [{key:row[key]for key in ['repository','commit','path']}],indent=2)+'\n')
        (args.out/'README.md').write_text('''# Original lean-mlir engine input

One complete original module at b8c4a771319a044854a4bbb49b8821381ef86ff8,
including all definitions, proofs, options and scoped syntax. No theorem or
tactic splitting, no admission/error removal, no source rewrite. All-mode,
reuse=false, unchanged engine default timeout (300s). These are prepared bytes,
not an executed native verification, profile, accepted theorem count or speedup.

Use the pinned nightly-2025-12-01 SDK and original root manifest/native import
paths; its correct Cli revision differs from the LeanMLIR subproject.
The stock frontend backend runs stdin, which has a different diagnostic/module
filename; compare it with original-path CLI before interpreting native outcomes.
The original root --tstack=400000 setting must be retained in both sides.
Profiler runs must preserve their own diagnostic settings/output/overhead,
rather than being pooled with uninstrumented performance clocks.

The retained original7808 candidate group keeps the only acquisition slot.
Do not start this input alongside it. New runs use the Rust dynamic48GiB
actual-RSS/CPU8-11 resource path without fixed per-process AS limits. No extra
AI agent, service, scheduler, CPU oracle or comparison system is invoked.
''')
        print(json.dumps(dict(candidates=1,source_bytes=len(row['text'].encode()),
            source_changed=False,new_native_executions=0)))
        return
    sources=sorted((row for row in rows if row['path'].startswith('datasets/verina/')
        and row['path'].endswith('/task.lean')),key=lambda row:row['path'])
    assert len(sources)==189
    assert {row['repository']for row in sources}=={'sunblaze-ucb/verina'}
    assert {row['commit']for row in sources}=={'66b3ce5014edafb20cb26b87c681e7f31847249f'}
    candidates=[dict(id=Path(row['path']).parent.name,task_id=None,code=row['text'],
        timeout_ms=120000,reuse=False)for row in sources]
    assert len({row['id']for row in candidates})==189
    args.out.mkdir(exist_ok=False)
    with gzip.open(args.out/'all.json.gz','xt',encoding='utf8') as stream:
        json.dump(dict(mode='all',candidates=candidates),stream,ensure_ascii=False)
        stream.write('\n')
    manifest=[{key:row[key]for key in ['repository','commit','path']}for row in sources]
    (args.out/'source-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    (args.out/'README.md').write_text("""# Original Verina engine inputs

All189official reference task.lean files at66b3ce5014edafb20cb26b87c681e7f31847249f.
Source text/order,ID and repository-relative filename mapping retained; no
sorry/admit/error removal. Batch all-mode,120s original synchronous timeout,
reuse=false. No task competition, cached zero-time proof or filename rewrite
inside the source. No native verifier/model/solver runs during preparation.

Use the NativeLean backend with exact4.18.0/Mathlibaa936c36 context. Stdin source
has a different diagnostic filename than original-path CLI; path-dependent code
requires explicit same-context differential qualification before full pairing.
The source manifest retains original filenames; it does not make stdin path
semantics identical.139admitted stubs and4API errors stay in the population.
Old results remain historical; do not mix old24GiB/2worker clocks with new
dynamic48GiB/four eligible cores. Do not start another native acquisition while
the existing sole original7808group is alive. Preparation is not a performance
result, proof completeness claim or reproduction of another prover system.
""")
    print(json.dumps(dict(candidates=len(candidates),source_bytes=sum(len(c['code'].encode())
        for c in candidates),source_changed=False,new_native_executions=0)))

if __name__=='__main__':
    main()
