"""Source preparation controls; no Lean or solver is executed."""
import gzip
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

ROOT=Path(__file__).resolve().parents[1]
PREPARE=ROOT/'bench/lean-code-verification/prepare-engine.py'
TARGET='SSA/Projects/SLLVM/Evaluation/AliveAutoGeneratedCopy.lean'
PIN='b8c4a771319a044854a4bbb49b8821381ef86ff8'

def source(path,text):
    return dict(repository='opencompl/lean-mlir',commit=PIN,path=path,text=text)

def run_prepare(directory,rows,*options):
    archive=directory/'source.jsonl.gz'
    with gzip.open(archive,'wt',encoding='utf8')as stream:
        for row in rows:
            stream.write(json.dumps(row,ensure_ascii=False)+'\n')
    output=directory/'prepared'
    run=subprocess.run([sys.executable,str(PREPARE),'--workload','leanmlir',
        '--input',str(archive),'--out',str(output),*options],
        capture_output=True,text=True)
    return run,output

class CodeSourceInputs(unittest.TestCase):
    def test_multiple_files_keep_original_bytes_admissions_and_separate_batches(self):
        rows=[source(TARGET,'import Lean\nexample : True := by bv_decide\n'),
            source('Blase/Model.lean','-- α comment\nexample : False := by sorry\nexample : True := by bv_decide\n'),
            source('CommentOnly.lean','/- bv_decide /- nested -/ -/\nexample : True := by trivial\n')]
        with tempfile.TemporaryDirectory()as tmp:
            run,out=run_prepare(Path(tmp),rows,'--bv-decide-files')
            self.assertEqual(run.returncode,0,run.stderr)
            self.assertEqual(json.loads(run.stdout)['candidates'],2)
            manifest=json.loads((out/'source-manifest.json').read_text())
            self.assertEqual([row['path']for row in manifest],['Blase/Model.lean',TARGET])
            original={row['path']:row['text']for row in rows}
            for row in manifest:
                batch=json.loads(gzip.decompress((out/row['input']).read_bytes()))
                self.assertEqual(batch['mode'],'all')
                self.assertEqual(len(batch['candidates']),1)
                candidate=batch['candidates'][0]
                self.assertEqual(candidate['id'],row['path'])
                self.assertEqual(candidate['code'].encode(),original[row['path']].encode())
                self.assertFalse(candidate['reuse'])
                self.assertNotIn('timeout_ms',candidate)
            self.assertFalse((out/'all.json.gz').exists())

    def test_default_single_module_recipe_stays_unchanged(self):
        rows=[source(TARGET,'import Lean\nexample : True := by bv_decide\n'),
            source('Other.lean','import Lean\nexample : True := by bv_decide\n')]
        with tempfile.TemporaryDirectory()as tmp:
            run,out=run_prepare(Path(tmp),rows)
            self.assertEqual(run.returncode,0,run.stderr)
            batch=json.loads(gzip.decompress((out/'all.json.gz').read_bytes()))
            self.assertEqual(batch,dict(mode='all',candidates=[
                dict(id=TARGET,task_id=None,code=rows[0]['text'],reuse=False)]))
            self.assertEqual(json.loads((out/'source-manifest.json').read_text()),
                [{key:rows[0][key]for key in ['repository','commit','path']}])

    def test_new_selector_cannot_silently_change_verina(self):
        run=subprocess.run([sys.executable,str(PREPARE),'--workload','verina',
            '--input','not-read','--out','not-created','--bv-decide-files'],
            capture_output=True,text=True)
        self.assertEqual(run.returncode,2)
        self.assertIn('requires --workload leanmlir',run.stderr)

if __name__=='__main__':
    unittest.main()
