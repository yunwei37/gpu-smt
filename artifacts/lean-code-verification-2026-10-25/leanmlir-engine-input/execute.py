"""Manual original lean-mlir file/stdin/profile run after original71retires.
Reuses existing Rust backend,watchdog,full stderr and closed-stream archival.
No theorem splitting,observer implementation,wait loop or additional scheduler.
"""
from pathlib import Path
import datetime,gzip,importlib.util,json,os,resource,subprocess,sys,time
REPO=Path('/workspaces/repository')
HERE=REPO/'artifacts/lean-code-verification-2026-10-25/leanmlir-engine-input'
ROOT=Path('/tmp/gpu-smt-code-verification-20261025')
PROJECT=ROOT/'lean-mlir'
SDK=ROOT/'leanmlir-sdk/lean-4.27.0-nightly-2025-12-01-linux'
SOURCE=Path('SSA/Projects/SLLVM/Evaluation/AliveAutoGeneratedCopy.lean')
CLI=Path('/tmp/gpu-smt-rust-engine-build-20261025/target/debug/gpu-smt')
sys.dont_write_bytecode=True
SPEC=importlib.util.spec_from_file_location('original71_execution',
 REPO/'artifacts/hotspot-mechanisms-2026-10-25/prepared71-20261026/execute.py')
ARCHIVE=importlib.util.module_from_spec(SPEC);SPEC.loader.exec_module(ARCHIVE)
CELLS=['original-file','stdin','original-file-profile']
def now():return datetime.datetime.now(datetime.timezone.utc).isoformat()
def main():
 batch=json.loads(gzip.decompress((HERE/'all.json.gz').read_bytes()))
 assert batch['mode']=='all' and len(batch['candidates'])==1
 candidate=batch['candidates'][0]
 assert candidate['code'].encode()==(PROJECT/SOURCE).read_bytes()
 assert candidate.get('timeout_ms',300000)==300000 and candidate['reuse'] is False
 assert '--tstack=400000' in (PROJECT/'lakefile.toml').read_text()
 assert SDK.joinpath('bin/lean').is_file() and SDK.joinpath('bin/lake').is_file()
 assert resource.getrlimit(resource.RLIMIT_AS)==(-1,-1)
 if sys.argv[1:]==['--validate-only']:
  print(json.dumps({'UTC':now(),'original_source_bytes':len(candidate['code'].encode()),
   'input_source_byte_equal':True,'candidate_id':candidate['id'],'cells':CELLS,
   'native_executions':0,'resource_point':'one exclusive4core lease,CPU8-11,actual48GiB,noAScap',
   'source_unchanged':True,'runtime_qualification_pending':True}));return
 assert not sys.argv[1:]
 prior=json.loads(Path(Path('/tmp/gpu-smt-active-original71-context.txt').read_text()).read_text())
 priorout=Path(prior['runtime_output'])
 terminal=json.loads((priorout/'terminal.json').read_text())
 assert terminal['exit_code']==0
 assert ARCHIVE.birth(prior['controller_pid'])!=prior['controller_start_ticks']
 for p in priorout.glob('*/launch.json'):
  launch=json.loads(p.read_text())
  assert ARCHIVE.birth(launch['pid'])!=launch['start_ticks']
 # No pinned old/next research native executable may still own a candidate.
 old=json.loads(Path('/tmp/gpu-smt-isolated42-20261026/context.json').read_text())['previous_manifest']
 pinned={old['repl'],old['prepared_host'],str(Path(old['sysroot'])/'bin/lean'),str(SDK/'bin/lean')}
 for p in Path('/proc').iterdir():
  if not p.name.isdigit():continue
  try:argv=(p/'cmdline').read_bytes().split(b'\0')[0].decode(errors='replace')
  except OSError:continue
  assert argv not in pinned,('existing research native owner',p.name)
 os.sched_setaffinity(0,{8,9,10,11})
 stamp=datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%dT%H%M%SZ')
 out=Path('/tmp')/('gpu-smt-leanmlir-native-'+stamp);out.mkdir()
 print(str(out),flush=True)
 env=dict(os.environ,PATH=str(SDK/'bin')+':/usr/local/cargo/bin:'+os.environ['PATH'],
  LEAN_SYSROOT=str(SDK),CARGO_HOME='/usr/local/cargo',RUSTUP_HOME='/usr/local/rustup',
  CARGO_TARGET_DIR='/tmp/gpu-smt-rust-engine-build-20261025/target',CARGO_BUILD_JOBS='1')
 env.pop('LEAN_PATH',None)
 started=time.monotonic()
 # Read configured import paths from existing Lake;no target/build substitution.
 command=[str(SDK/'bin/lake'),'--no-build','env','printenv','LEAN_PATH']
 config=subprocess.run(command,cwd=PROJECT,env=env,stdout=subprocess.PIPE,stderr=subprocess.PIPE)
 (out/'lake-env.stdout').write_bytes(config.stdout);(out/'lake-env.stderr').write_bytes(config.stderr)
 (out/'lake-env.json').write_text(json.dumps({'UTC':now(),'command':command,'exit_code':config.returncode})+'\n')
 config.check_returncode()
 env['LEAN_PATH']=config.stdout.decode().strip()
 assert env['LEAN_PATH'] and '\n' not in env['LEAN_PATH']
 # Old group fully retired before rebuilding;do not replace a live capture CLI.
 build=['/usr/local/cargo/bin/cargo','build','--locked','-p','gpu-smt-server','--bin','gpu-smt']
 with (out/'build.log').open('wb')as f:
  code=subprocess.call(build,cwd=REPO,env=env,stdout=f,stderr=subprocess.STDOUT)
 (out/'build.json').write_text(json.dumps({'UTC':now(),'command':build,'exit_code':code,
  'source':subprocess.check_output(['git','rev-parse','HEAD'],cwd=REPO,text=True).strip()})+'\n')
 if code:raise SystemExit(code)
 manifest={'UTC':now(),'controller_pid':os.getpid(),'controller_start_ticks':ARCHIVE.birth(os.getpid()),
  'original71terminal':terminal,'SDK':str(SDK),'project':str(PROJECT),'original_source_path':str(SOURCE),
  'LEAN_PATH':env['LEAN_PATH'],'source_bytes':len(candidate['code'].encode()),'cells':CELLS,
  'resources':{'actual_RSS_budget_bytes':48*1024**3,'cpu_ids':[8,9,10,11],'cores_per_worker':4,'fixed_AS_limit':False},
  'scope':'full unchanged original module;300s engine default,not a published workload deadline;single native candidate percell'}
 (out/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
 for name in CELLS:
  cell=out/name;cell.mkdir();stderr=cell/'native-stderr';stderr.mkdir()
  cmd=[str(CLI),'check','--lean',str(SDK/'bin/lean'),'--project',str(PROJECT),
   '--environment','leanmlir-b8c4a771-nightly20251201-original48GiB-4core',
   '--cpus','8,9,10,11','--worker-cores','4','--memory-gib','48',
   '--lean-arg','--tstack=400000','--stderr-dir',str(stderr)]
  if name!='stdin':cmd+=['--source-file',str(SOURCE)]
  profile=cell/'native-trace.json'
  if name.endswith('-profile'):
   for arg in ['-Dtrace.profiler=true','-Dtrace.profiler.output='+str(profile),'-Dtrace.profiler.output.pp=true']:
    cmd+=['--lean-arg',arg]
  inp=cell/'input.jsonl';inp.write_text(json.dumps(batch)+'\n')
  begin=time.monotonic()
  with inp.open('rb')as src,(cell/'results.jsonl').open('wb')as result,(cell/'resource-events.jsonl').open('wb')as events:
   p=subprocess.Popen(cmd,cwd=PROJECT,env=env,stdin=src,stdout=result,stderr=events,start_new_session=True)
   (cell/'launch.json').write_text(json.dumps({'UTC':now(),'pid':p.pid,'start_ticks':ARCHIVE.birth(p.pid),'command':cmd,
    'binary_bytes':CLI.stat().st_size,'binary_mtime':CLI.stat().st_mtime},indent=2)+'\n')
   code=p.wait()
  (cell/'terminal.json').write_text(json.dumps({'UTC':now(),'exit_code':code,'cell_seconds':time.monotonic()-begin,
   'profiler_output_exists':profile.exists(),'scope':'wholemodule CLI setup,queue,verification,fallback if any andretirement;archival separatelytimed'})+'\n')
  a=time.monotonic()
  for f in list(stderr.glob('*.stderr'))+[inp,cell/'results.jsonl',cell/'resource-events.jsonl']+([profile]if profile.exists()else[]):
   ARCHIVE.archive_closed(f)
  (cell/'archival.json').write_text(json.dumps({'UTC':now(),'seconds':time.monotonic()-a,'closed_streams_losslessly_preserved':True})+'\n')
  if code:raise SystemExit(code)
 (out/'terminal.json').write_text(json.dumps({'UTC':now(),'exit_code':0,'controller_seconds':time.monotonic()-started,
  'scope':'includes environment lookup,build,startup,all threecells,cleanup andarchival;profile overhead separatefrom uninstrumented clocks'})+'\n')
if __name__=='__main__':main()
